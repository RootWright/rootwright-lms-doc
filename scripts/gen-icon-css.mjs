// Regenerates docs/.vitepress/theme/styles/icons.css from theme/icons.js.
// Run after adding an icon: npm run icons:css
import { writeFileSync, mkdirSync } from 'node:fs'
import { icons } from '../docs/.vitepress/theme/icons.js'

const svg = (d) =>
  `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='1.9' stroke-linecap='round' stroke-linejoin='round'><path d='${d}'/></svg>`
const uri = (d) => `url("data:image/svg+xml,${encodeURIComponent(svg(d)).replace(/'/g, '%27')}")`

let css = '/* Generated by scripts/gen-icon-css.mjs — do not edit by hand. */\n'
css += '.rw-mi{display:inline-block;width:1em;height:1em;background:currentColor;-webkit-mask:var(--rw-icon) center/contain no-repeat;mask:var(--rw-icon) center/contain no-repeat;flex-shrink:0}\n'
css += ':root{\n'
for (const [name, d] of Object.entries(icons)) css += `  --rw-icon-${name}:${uri(d)};\n`
css += '}\n'
for (const name of Object.keys(icons)) css += `.rw-i-${name}{--rw-icon:var(--rw-icon-${name})}\n`
mkdirSync('docs/.vitepress/theme/styles', { recursive: true })
writeFileSync('docs/.vitepress/theme/styles/icons.css', css)
console.log('icons.css written:', Object.keys(icons).length, 'icons')
